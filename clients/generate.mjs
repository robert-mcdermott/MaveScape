// Writes the R and Python clients' functions for every MaveScape action from clients/tools.json
// (the actions' names, titles, descriptions and argument schemas, which a Go test keeps equal to
// actions.go): clients/python/src/mavescape/_tools.py, clients/r/R/tools.R with a help page per
// function in clients/r/man/, the R NAMESPACE, and both packages' versions (main.go's). With
// --check it writes nothing and fails when a file differs (CI). After CytoWeave 0.8.0's
// clients/generate.mjs (wave 7, slice 4).
//
//   go test -run TestTheClientsToolListIsCurrent -update   # after changing an action in actions.go
//   node clients/generate.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const check = process.argv.includes('--check');
const tools = JSON.parse(readFileSync(join(here, 'tools.json'), 'utf8'));
const version = /^var version = "([^"]+)"$/m.exec(readFileSync(join(root, 'main.go'), 'utf8'))[1];
const HEADER = 'Generated by clients/generate.mjs from clients/tools.json; do not edit by hand.';
// The clients' own functions, which no action may shadow (ms.call, ms_tools, …).
const OWN = new Set(['call', 'tools', 'version', 'url', 'token', 'client', 'timeout', 'connect', 'default', 'save_image', 'images']);
const clash = tools.filter((t) => OWN.has(t.name)).map((t) => t.name);
if (clash.length) throw new Error(`Actions named like the clients' own functions: ${clash.join(', ')}. Rename them in actions.go.`);

// The actions that give pictures (wave 7, slice 3), and the argument that asks for one (none: the
// action always does): their functions take file, which saves the picture as a PNG.
const PICTURES = { render_map: 'image', render_structure: null, figures: 'image' };
const pictures = (tool) => Object.hasOwn(PICTURES, tool.name);

const PYTHON_KEYWORDS = new Set(['and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif', 'else', 'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or', 'pass', 'raise', 'return', 'try', 'while', 'with', 'yield', 'self', 'file']);
const R_RESERVED = new Set(['if', 'else', 'repeat', 'while', 'function', 'for', 'next', 'break', 'TRUE', 'FALSE', 'NULL', 'Inf', 'NaN', 'NA', 'in', 'ms', 'file']);

// The arguments of an action: the required ones first, in the order the action lists them
// (positional in R and Python), then the others by name.
function argumentsOf(tool) {
  const properties = tool.inputSchema.properties ?? {};
  const required = tool.inputSchema.required ?? [];
  return [
    ...required.map((name) => ({ name, spec: properties[name], required: true })),
    ...Object.entries(properties).filter(([name]) => !required.includes(name)).map(([name, spec]) => ({ name, spec, required: false })),
  ];
}

function describeType(spec) {
  if (spec.enum) return `one of ${spec.enum.map((v) => `"${v}"`).join(', ')}`;
  if (spec.type === 'array') return spec.items?.type === 'integer' ? 'a vector of whole numbers (Python: a list)' : 'a vector of strings (Python: a list)';
  if (spec.type === 'object') return 'a named list (Python: a dict)';
  if (spec.type === 'boolean') return 'TRUE or FALSE (Python: True or False)';
  if (spec.type === 'integer') return 'a whole number';
  if (spec.type === 'number') return 'a number';
  if (spec.type === 'string') return 'a string';
  return 'any value';
}

// A description as a sentence followed by a space, or nothing when there is none.
const sentence = (text) => (!text ? '' : /[.!?]$/.test(text) ? `${text} ` : `${text}. `);
const FILE_HELP = 'Optional; save the picture to this path as a PNG file (and ask for it).';

function wrapText(text, width, indent) {
  const words = text.split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines.map((l) => `${indent}${l}`).join('\n');
}

// --- Python -------------------------------------------------------------------------------------

const pythonName = (name) => (PYTHON_KEYWORDS.has(name) ? `${name}_` : name);

function pythonTools() {
  const out = [`# ${HEADER}`, '', '"""Every MaveScape action as a method; MaveScape (client.py) adds the connection."""', '', '', 'class Tools:', '    """The actions of MaveScape\'s remote control, one method each."""', ''];
  for (const tool of tools) {
    const args = argumentsOf(tool);
    const params = ['self'];
    let keywordOnly = false;
    for (const a of args) {
      if (!a.required && !keywordOnly) {
        params.push('*');
        keywordOnly = true;
      }
      params.push(a.required ? pythonName(a.name) : `${pythonName(a.name)}=None`);
    }
    if (pictures(tool)) {
      if (!keywordOnly) params.push('*');
      params.push('file=None');
    }
    out.push(`    def ${tool.name}(${params.join(', ')}):`);
    out.push(`        """${tool.title}.`, '', wrapText(tool.description.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"'), 92, '        '));
    if (args.length || pictures(tool)) {
      out.push('', '        Args:');
      for (const a of args) out.push(wrapText(`${pythonName(a.name)}: ${sentence(a.spec.description ?? '')}${a.required ? 'Required' : 'Optional'}; ${describeType(a.spec)}.`, 88, '            ').replace(/\n {12}/g, '\n                '));
      if (pictures(tool)) out.push(`            file: ${FILE_HELP}`);
    }
    out.push('', '        Returns:', '            A Result: the message and the data MaveScape answered with.', '        """');
    const mapping = args.map((a) => `"${a.name}": ${pythonName(a.name)}`).join(', ');
    if (pictures(tool)) {
      const flag = PICTURES[tool.name];
      if (flag) out.push(`        if file is not None and ${pythonName(flag)} is None:`, `            ${pythonName(flag)} = True`);
      out.push(`        result = self.call("${tool.name}"${mapping ? `, **{${mapping}}` : ''})`, '        if file is not None:', '            result.save_image(file)', '        return result', '');
    } else {
      out.push(`        return self.call("${tool.name}"${mapping ? `, **{${mapping}}` : ''})`, '');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

// --- R ------------------------------------------------------------------------------------------

const rName = (name) => (R_RESERVED.has(name) ? `${name}_` : name);

// Rd text: backslash, braces and percent escaped.
const rd = (text) => String(text).replace(/\\/g, '\\\\').replace(/([{}%])/g, '\\$1');
const roxygen = (text) => String(text).replace(/%/g, '\\%');

function rUsage(tool) {
  const args = argumentsOf(tool);
  const parts = args.map((a) => (a.required ? rName(a.name) : `${rName(a.name)} = NULL`));
  if (pictures(tool)) parts.push('file = NULL');
  parts.push('ms = ms_default()');
  return `ms_${tool.name}(${parts.join(', ')})`;
}

function rTools() {
  const out = [`# ${HEADER}`, ''];
  for (const tool of tools) {
    const args = argumentsOf(tool);
    out.push(`#' ${roxygen(tool.title)}`, "#'", ...wrapText(roxygen(tool.description), 92, "#' ").split('\n'), "#'");
    for (const a of args) out.push(...wrapText(roxygen(`@param ${rName(a.name)} ${sentence(a.spec.description ?? '')}${a.required ? 'Required' : 'Optional'}; ${describeType(a.spec)}.`), 92, "#' ").split('\n'));
    if (pictures(tool)) out.push(`#' @param file ${FILE_HELP}`);
    out.push("#' @param ms A connection from ms_connect() (default: the last one made).", "#' @return A mavescape_result: the message and the data MaveScape answered with.", "#' @export");
    const signature = rUsage(tool).replace(/^ms_[a-z_]+\(/, '').replace(/\)$/, '');
    out.push(`ms_${tool.name} <- function(${signature}) {`);
    const flag = PICTURES[tool.name];
    if (flag) out.push(`  if (!is.null(file) && is.null(${rName(flag)})) ${rName(flag)} <- TRUE`);
    const values = args.map((a) => {
      const value = a.spec.type === 'array' ? `.ms_array(${rName(a.name)})` : rName(a.name);
      return `${/^[A-Za-z][A-Za-z0-9_.]*$/.test(a.name) ? a.name : `\`${a.name}\``} = ${value}`;
    });
    const call = `ms_call("${tool.name}", ${values.length ? `${values.join(', ')}, ` : ''}ms = ms)`;
    if (pictures(tool)) out.push(`  result <- ${call}`, '  if (!is.null(file)) ms_save_image(result, file)', '  result', '}', '');
    else out.push(`  ${call}`, '}', '');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

function rHelpPage(tool) {
  const args = argumentsOf(tool);
  const items = args.map((a) => `\\item{${rName(a.name)}}{${rd(`${sentence(a.spec.description ?? '')}${a.required ? 'Required' : 'Optional'}; ${describeType(a.spec)}.`)}}`);
  if (pictures(tool)) items.push(`\\item{file}{${rd(FILE_HELP)}}`);
  items.push('\\item{ms}{A connection from \\code{\\link{ms_connect}} (default: the last one made).}');
  return [
    `% ${HEADER}`,
    `\\name{ms_${tool.name}}`,
    `\\alias{ms_${tool.name}}`,
    `\\title{${rd(tool.title)}}`,
    '\\usage{',
    rUsage(tool),
    '}',
    '\\arguments{',
    ...items,
    '}',
    '\\value{',
    'A \\code{mavescape_result}: the \\code{message} and the \\code{data} MaveScape answered with.',
    '}',
    '\\description{',
    rd(tool.description),
    '}',
    `\\seealso{\\code{\\link{ms_call}}, which sends any action by its name (here \\code{"${tool.name}"}).}`,
    '',
  ].join('\n');
}

function rNamespace() {
  const core = ['ms_call', 'ms_connect', 'ms_default', 'ms_images', 'ms_save_image', 'ms_tools'];
  return [
    `# ${HEADER}`,
    ...[...core, ...tools.map((t) => `ms_${t.name}`)].sort().map((name) => `export(${name})`),
    'S3method(as.data.frame,mavescape_result)',
    'S3method(print,mavescape)',
    'S3method(print,mavescape_result)',
    '',
  ].join('\n');
}

// --- Writing ------------------------------------------------------------------------------------

const files = new Map();
files.set('python/src/mavescape/_tools.py', pythonTools());
files.set('r/R/tools.R', rTools());
files.set('r/NAMESPACE', rNamespace());
for (const tool of tools) files.set(`r/man/ms_${tool.name}.Rd`, rHelpPage(tool));
// Versions: the program's.
const pyproject = readFileSync(join(here, 'python/pyproject.toml'), 'utf8');
files.set('python/pyproject.toml', pyproject.replace(/^version = "[^"]*"$/m, `version = "${version}"`));
const description = readFileSync(join(here, 'r/DESCRIPTION'), 'utf8');
files.set('r/DESCRIPTION', description.replace(/^Version: .*$/m, `Version: ${version}`));
const init = readFileSync(join(here, 'python/src/mavescape/__init__.py'), 'utf8');
files.set('python/src/mavescape/__init__.py', init.replace(/^__version__ = "[^"]*"$/m, `__version__ = "${version}"`));

// Help pages of actions that no longer exist.
const generatedPages = existsSync(join(here, 'r/man')) ? readdirSync(join(here, 'r/man')).filter((f) => f.endsWith('.Rd') && readFileSync(join(here, 'r/man', f), 'utf8').includes(HEADER)) : [];
const stale = generatedPages.filter((f) => !files.has(`r/man/${f}`));

const differ = [];
for (const [path, text] of files) {
  const full = join(here, path);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (current === text) continue;
  differ.push(path);
  if (!check) {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, text);
  }
}
for (const f of stale) {
  differ.push(`r/man/${f} (no such action)`);
  if (!check) rmSync(join(here, 'r/man', f));
}
if (check) {
  if (differ.length) {
    console.error(`The clients are out of date with clients/tools.json or main.go: ${differ.join(', ')}. Run node clients/generate.mjs.`);
    process.exit(1);
  }
  console.log(`The clients' ${tools.length} action functions and version ${version} are current.`);
} else {
  console.log(differ.length ? `Wrote ${differ.length} file(s): ${differ.slice(0, 6).join(', ')}${differ.length > 6 ? ', …' : ''}` : 'Nothing to change.');
}
